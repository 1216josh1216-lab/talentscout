#!/usr/bin/env node
// Runs the protected-attribute ablation and the masking audit on the
// synthetic dataset. Writes docs/ABLATION.md. Exits 1 if any score moved.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as pdfjsLib from 'pdfjs-dist/legacy/build/pdf.mjs';
import mammoth from 'mammoth';
import { PROFILES } from './dataset/profiles.mjs';
import { renderResume } from './dataset/render.mjs';
import { runAblation, auditMasking } from './dataset/ablation.mjs';
import { HELD_OUT } from './dataset/heldout.mjs';
import { HELD_OUT_2 } from './dataset/heldout2.mjs';
import { analyzeResume } from '../src/engine/score.js';
import { parseRulesJson } from '../src/engine/rules.js';
import { parseResumeFile } from '../src/parsers/index.js';
import { makePdf } from '../tests/helpers/makePdf.js';
import { makeDocx } from '../tests/helpers/makeDocx.js';

const root = new URL('..', import.meta.url);
const dir = (rel) => fileURLToPath(new URL(rel, root));
const libs = { pdfjsLib, mammoth, cMapUrl: dir('node_modules/pdfjs-dist/cmaps/'), standardFontDataUrl: dir('node_modules/pdfjs-dist/standard_fonts/') };
const rules = parseRulesJson(readFileSync(new URL('data/synthetic/job.rules.json', root), 'utf8')).rules;

const on = runAblation(rules, { protectedMode: true });
const off = runAblation(rules, { protectedMode: false });
const audit = auditMasking(rules);

// Photo as an embedded image: the extracted text must be byte-identical.
let photoChecked = 0;
const photoDiffs = [];
for (const p of PROFILES.filter((x) => x.format !== 'txt')) {
  const { lines } = renderResume(p);
  const make = p.format === 'pdf' ? makePdf : makeDocx;
  const plain = await parseResumeFile({ name: `a.${p.format}`, bytes: make(lines) }, libs);
  const withPhoto = await parseResumeFile({ name: `b.${p.format}`, bytes: make(lines, { photo: true }) }, libs);
  photoChecked++;
  // The image sits in its own paragraph, so ignore blank lines when comparing.
  const words = (t) => t.split('\n').filter((l) => l.trim()).join('\n');
  if (plain.error || withPhoto.error || words(plain.text) !== words(withPhoto.text)) photoDiffs.push(p.id);
}

// Held-out identity formats: not used while writing or fixing the detector.
const runHeld = (set) => set.map((h) => {
  const a = analyzeResume(h.text, rules, { protectedMode: true });
  return { ...h, results: h.hidden.map(([type, value]) => ({ type, value, visible: a.text.includes(value.normalize('NFKC')) })) };
});
const held = runHeld(HELD_OUT);
const heldAll = held.flatMap((h) => h.results);
const heldMasked = heldAll.filter((r) => !r.visible).length;
const held2 = runHeld(HELD_OUT_2);
const held2All = held2.flatMap((h) => h.results);
const held2Masked = held2All.filter((r) => !r.visible).length;
const heldTable = (set) => `| Format | Attribute | Value | Result |\n|---|---|---|---|\n${set.flatMap((h) => h.results.map((r) => `| ${h.note} | ${r.type} | \`${r.value}\` | ${r.visible ? '**visible**' : 'hidden'} |`)).join('\n')}`;

const perVariant = (res) => {
  const out = {};
  for (const c of res.changed) out[c.variant] = (out[c.variant] ?? 0) + 1;
  return out;
};
const variants = ['name', 'gender', 'age', 'photo', 'all', 'keyword_name'];
const label = { name: 'Different name (and email)', gender: 'Different gender', age: 'Different age and birth date', photo: 'Photo line added or removed', all: 'All of the above at once', keyword_name: 'Name replaced by a keyword ("Docker Java", "容器化")' };
const onBy = perVariant(on);
const offBy = perVariant(off);
const n = PROFILES.length;

const md = `# Protected-attribute ablation

Generated by \`npm run ablation\`. Do not edit by hand.

## Question 1: does the score move?

Each of the ${n} synthetic resumes is re-rendered from its hidden profile with
only a protected attribute changed. Everything else is identical. The total,
every rule's points and the status flags must be exactly equal.

| Change | Resumes | Score changed, mode ON | Score changed, mode OFF |
|---|---|---|---|
${variants.map((v) => `| ${label[v]} | ${n} | ${onBy[v] ?? 0} | ${offBy[v] ?? 0} |`).join('\n')}
| **Total** | **${on.checked}** | **${on.changed.length}** | **${off.changed.length}** |

The last row of changes is deliberate: a name that is also a keyword. With
masking OFF it changes ${offBy.keyword_name ?? 0} scores, which shows the test is able to fail.

**Photo as an embedded image:** ${photoChecked} PDF and DOCX resumes were written twice,
with and without an image. Extracted text (ignoring blank lines) differed in ${photoDiffs.length}.
The parsers extract text only; image data is never read.

${on.changed.length ? `### Failures with mode ON\n\n| Resume | Change | Before | After |\n|---|---|---|---|\n${on.changed.map((c) => `| ${c.id} (${c.lang}, header style ${c.header}) | ${c.variant} | ${c.base} | ${c.got} |`).join('\n')}\n` : ''}
## Question 2: is each value actually hidden?

A stricter check. A value can stay visible without changing the score, but it
could then appear in an evidence quote. For every protected value the
generator wrote, is it absent from the text the rules see?

| Attribute | Values written | Masked | Still visible |
|---|---|---|---|
${Object.entries(audit.byType).map(([t, v]) => `| ${t} | ${v.total} | ${v.masked} | ${v.total - v.masked} |`).join('\n')}

${audit.leaks.length ? `### Values still visible\n\n| Resume | Attribute | Text |\n|---|---|---|\n${audit.leaks.map((l) => `| ${l.id} (${l.lang}, header style ${l.header}) | ${l.type} | \`${l.snippet}\` |`).join('\n')}\n` : 'No value was left visible.\n'}
## Question 3: what about formats the detector was not tuned on?

Two rounds of held-out formats. Each round was written after the detector
was last changed, run once, and recorded before any further change.

### Round 1: unusual header formats

First run, before hardening: **10 of 23 values hidden.** That result led to a
structural change: in protected mode the whole header block above the first
section heading is hidden from every rule, whatever it contains. Round 1 is
therefore no longer held out. Re-run after the change: **${heldMasked} of ${heldAll.length} hidden.**

${heldTable(held)}

### Round 2: identity details outside the header

Written after the hardening, to probe what the header rule cannot cover:
summaries, experience bullets, footers, URLs, and resumes with no headings.
Run once: **${held2Masked} of ${held2All.length} values hidden.** The detector was not changed afterwards.

${heldTable(held2)}

Round 2 is the realistic number for identity details that appear in running
text. Hiding those reliably needs language understanding that a rule-based
tool does not have.

## What this does and does not show

- It shows score invariance on these ${n} resumes and ${on.checked} variants, across
  ${new Set(PROFILES.map((p) => `${p.lang}${p.header}`)).size} header styles in two languages. It is a test, not a mathematical proof.
- The header styles were written by the same author as the detector. Real
  resumes will contain formats that are not covered here.
- Graduation year (a proxy for age) and school tier are scored by design.
  This test does not, and cannot, show that they are free of bias.
`;
writeFileSync(new URL('docs/ABLATION.md', root), md);

console.log(`mode ON : ${on.changed.length} of ${on.checked} variants changed the score`);
for (const c of on.changed) console.log(`   ${c.id} ${c.lang} header ${c.header} ${c.variant}: ${c.base} -> ${c.got}`);
console.log(`mode OFF: ${off.changed.length} of ${off.checked} variants changed the score (${JSON.stringify(offBy)})`);
console.log(`photo image: ${photoDiffs.length} of ${photoChecked} files differ`);
console.log(`masking audit: ${Object.entries(audit.byType).map(([t, v]) => `${t} ${v.masked}/${v.total}`).join(', ')}`);
for (const l of audit.leaks) console.log(`   visible: ${l.id} ${l.lang} header ${l.header} ${l.type} "${l.snippet}"`);
console.log(`held-out round 1 (after hardening): ${heldMasked} of ${heldAll.length} values hidden`);
console.log(`held-out round 2 (first run): ${held2Masked} of ${held2All.length} values hidden`);
for (const h of [...held, ...held2]) for (const r of h.results.filter((x) => x.visible)) console.log(`   visible: ${h.id} (${h.note}) ${r.type} "${r.value}"`);
console.log('wrote docs/ABLATION.md');
process.exit(on.changed.length || photoDiffs.length ? 1 : 0);
