#!/usr/bin/env node
// Evaluates the engine against a plain keyword baseline on the synthetic
// dataset, using the real file parsers. Writes docs/EVALUATION.md and
// data/synthetic/results.json.
//
// Task: predict `qualified` (has Python AND has SQL AND graduates in the window).
//   Engine   : no "missing must-have", no "outside window", graduation year found.
//   Baseline : the text contains "python" and "sql" (any case, anywhere, as
//              substrings) and contains one of the window years as a string.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as pdfjsLib from 'pdfjs-dist/legacy/build/pdf.mjs';
import mammoth from 'mammoth';
import { parseResumeFile } from '../src/parsers/index.js';
import { analyzeResume } from '../src/engine/score.js';
import { parseRulesJson } from '../src/engine/rules.js';

const root = new URL('..', import.meta.url);
const dir = (rel) => fileURLToPath(new URL(rel, root));
const libs = { pdfjsLib, mammoth, cMapUrl: dir('node_modules/pdfjs-dist/cmaps/'), standardFontDataUrl: dir('node_modules/pdfjs-dist/standard_fonts/') };
const data = JSON.parse(readFileSync(new URL('data/synthetic/labels.json', root), 'utf8'));
const rules = parseRulesJson(readFileSync(new URL('data/synthetic/job.rules.json', root), 'utf8')).rules;
const years = [];
for (let y = data.window.from; y <= data.window.to; y++) years.push(String(y));

export function baselinePredict(text) {
  const t = text.toLowerCase();
  return t.includes('python') && t.includes('sql') && years.some((y) => t.includes(y));
}
export function enginePredict(a) {
  return a.readable && a.eligible && !a.flags.includes('grad_unknown');
}

function wilson(k, n) {
  if (!n) return [0, 0];
  const z = 1.96;
  const p = k / n;
  const d = 1 + (z * z) / n;
  const c = p + (z * z) / (2 * n);
  const h = z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n));
  return [(c - h) / d, (c + h) / d];
}
function metrics(rows, key) {
  let tp = 0, fp = 0, fn = 0, tn = 0;
  for (const r of rows) {
    if (r[key] && r.truth) tp++;
    else if (r[key] && !r.truth) fp++;
    else if (!r[key] && r.truth) fn++;
    else tn++;
  }
  const precision = tp + fp ? tp / (tp + fp) : 0;
  const recall = tp + fn ? tp / (tp + fn) : 0;
  return { tp, fp, fn, tn, precision, recall, f1: precision + recall ? (2 * precision * recall) / (precision + recall) : 0, accuracy: (tp + tn) / rows.length, precisionCI: wilson(tp, tp + fp), recallCI: wilson(tp, tp + fn) };
}

const rows = [];
for (const item of data.resumes) {
  const bytes = new Uint8Array(readFileSync(new URL(`data/synthetic/resumes/${item.file}`, root)));
  const parsed = await parseResumeFile({ name: item.file, bytes }, libs);
  if (parsed.error) throw new Error(`${item.file}: ${parsed.error} ${parsed.detail ?? ''}`);
  const a = analyzeResume(parsed.text, rules);
  rows.push({
    id: item.id,
    file: item.file,
    lang: item.lang,
    category: item.category,
    truth: item.truth.qualified,
    engine: enginePredict(a),
    baseline: baselinePredict(parsed.text),
    score: a.total,
    flags: a.flags,
    gradTruth: item.truth.graduation_year,
    gradFound: a.extracted.graduationYear,
    schoolTruth: item.truth.school,
    schoolFound: a.extracted.school,
    notes: `python: ${item.how_python_is_written}; sql: ${item.how_sql_is_written}; date: ${item.graduation_format}`,
  });
}

const pct = (x) => `${(x * 100).toFixed(1)}%`;
const ci = ([a, b]) => `${pct(a)}–${pct(b)}`;
const E = metrics(rows, 'engine');
const B = metrics(rows, 'baseline');
const byLang = Object.fromEntries(['en', 'zh'].map((l) => [l, { n: rows.filter((r) => r.lang === l).length, engine: metrics(rows.filter((r) => r.lang === l), 'engine'), baseline: metrics(rows.filter((r) => r.lang === l), 'baseline') }]));
const cats = [...new Set(rows.map((r) => r.category))];
const gradOk = rows.filter((r) => r.gradFound === r.gradTruth).length;
const schoolOk = rows.filter((r) => r.schoolFound === r.schoolTruth).length;
const errs = (key) => rows.filter((r) => r[key] !== r.truth);
const kind = (r, key) => (r[key] ? 'False positive' : 'False negative');

const line = (name, m) => `| ${name} | ${pct(m.precision)} (${m.tp}/${m.tp + m.fp}) | ${pct(m.recall)} (${m.tp}/${m.tp + m.fn}) | ${pct(m.f1)} | ${pct(m.accuracy)} | ${m.tp} | ${m.fp} | ${m.fn} | ${m.tn} |`;
const md = `# Evaluation

Generated by \`npm run evaluate\`. Do not edit by hand.

**Read this first.** The dataset is 50 *synthetic* resumes written by the same
project that wrote the engine. These numbers show how the rules behave on
known hard cases. They are not evidence of accuracy on real resumes, and
with n = 50 the intervals are wide.

## Task

Predict whether a candidate is **qualified**: really has Python, really has
SQL, and graduates in ${data.window.from}–${data.window.to}. Ground truth comes from the hidden
profile each resume was generated from (\`data/synthetic/labels.json\`), not
from any tool's output. ${rows.filter((r) => r.truth).length} of ${rows.length} are qualified.

- **TalentScout**: no "missing must-have", not outside the window, graduation year found.
- **Keyword baseline**: text contains "python" and "sql" (substring, any case) and the string "${years.join('" or "')}".

## Result

| System | Precision | Recall | F1 | Accuracy | TP | FP | FN | TN |
|---|---|---|---|---|---|---|---|---|
${line('TalentScout', E)}
${line('Keyword baseline', B)}

95% Wilson intervals — TalentScout: precision ${ci(E.precisionCI)}, recall ${ci(E.recallCI)}.
Baseline: precision ${ci(B.precisionCI)}, recall ${ci(B.recallCI)}.

### By language

| Language | n | System | Precision | Recall |
|---|---|---|---|---|
${['en', 'zh'].flatMap((l) => [`| ${l === 'en' ? 'English' : 'Chinese'} | ${byLang[l].n} | TalentScout | ${pct(byLang[l].engine.precision)} | ${pct(byLang[l].engine.recall)} |`, `| | | Keyword baseline | ${pct(byLang[l].baseline.precision)} | ${pct(byLang[l].baseline.recall)} |`]).join('\n')}

### By case type (correct / total)

| Case type | n | TalentScout | Keyword baseline |
|---|---|---|---|
${cats.map((c) => { const rs = rows.filter((r) => r.category === c); return `| ${c.replace(/_/g, ' ')} | ${rs.length} | ${rs.filter((r) => r.engine === r.truth).length} | ${rs.filter((r) => r.baseline === r.truth).length} |`; }).join('\n')}

### Field extraction (TalentScout only)

- Graduation year matches the profile: ${gradOk} / ${rows.length}
- School matches the profile (including "not in any tier"): ${schoolOk} / ${rows.length}

## Every TalentScout error

${errs('engine').length ? `| File | Error | How the resume was written | What the engine saw |\n|---|---|---|---|\n${errs('engine').map((r) => `| ${r.file} | ${kind(r, 'engine')} | ${r.notes} | flags: ${r.flags.join(', ') || 'none'}; graduation year found: ${r.gradFound ?? 'none'} |`).join('\n')}` : 'None.'}

## Every baseline error

${errs('baseline').length ? `| File | Error | How the resume was written |\n|---|---|---|\n${errs('baseline').map((r) => `| ${r.file} | ${kind(r, 'baseline')} | ${r.notes} |`).join('\n')}` : 'None.'}
`;

mkdirSync(new URL('docs/', root), { recursive: true });
writeFileSync(new URL('docs/EVALUATION.md', root), md);
writeFileSync(new URL('data/synthetic/results.json', root), JSON.stringify({ engine: E, baseline: B, byLanguage: byLang, graduationYearCorrect: gradOk, schoolCorrect: schoolOk, n: rows.length, rows }, null, 2) + '\n');

console.log(`n = ${rows.length} (${rows.filter((r) => r.truth).length} qualified)`);
console.log(`TalentScout      precision ${pct(E.precision)}  recall ${pct(E.recall)}  F1 ${pct(E.f1)}   TP ${E.tp} FP ${E.fp} FN ${E.fn} TN ${E.tn}`);
console.log(`Keyword baseline precision ${pct(B.precision)}  recall ${pct(B.recall)}  F1 ${pct(B.f1)}   TP ${B.tp} FP ${B.fp} FN ${B.fn} TN ${B.tn}`);
console.log(`graduation year correct ${gradOk}/${rows.length}, school correct ${schoolOk}/${rows.length}`);
for (const r of errs('engine')) console.log(`  engine ${kind(r, 'engine').toLowerCase()}: ${r.file} [${r.category}] ${r.notes} -> flags ${r.flags.join(',') || 'none'}`);
for (const r of errs('baseline')) console.log(`  baseline ${kind(r, 'baseline').toLowerCase()}: ${r.file} [${r.category}] ${r.notes}`);
console.log('wrote docs/EVALUATION.md and data/synthetic/results.json');
